export type MessageKey = keyof typeof zh

/** Fills `{name}` placeholders; list values are joined the way the locale writes lists. */
export function fill(template: string, values: Record<string, string | number | string[]> = {}, locale: Locale = "en") {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => {
    const value = values[key]
    if (value === undefined) return match
    return Array.isArray(value) ? value.join(locale === "zh" ? "、" : ", ") : String(value)
  })
}

export type Locale = "zh" | "en"
const MESSAGES: Record<Locale, Messages> = { zh, en }
const STORAGE_KEY = "ai-gateway-pool:locale"

const LocaleContext = createContext<{ locale: Locale; t: Messages; setLocale: (l: Locale) => void }>({
  locale: "en",
  t: en,
  setLocale: () => {},
})

function initialLocale(): Locale {
  const stored = localStorage.getItem(STORAGE_KEY)
  if (stored === "zh" || stored === "en") return stored
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en"
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale)
  const setLocale = (next: Locale) => {
    localStorage.setItem(STORAGE_KEY, next)
    document.documentElement.lang = next === "zh" ? "zh-CN" : "en"
    setLocaleState(next)
  }
  return <LocaleContext value={{ locale, t: MESSAGES[locale], setLocale }}>{children}</LocaleContext>
}

export const useI18n = () => useContext(LocaleContext)
